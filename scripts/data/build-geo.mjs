#!/usr/bin/env node
/**
 * One-time generator for two committed, small data files:
 *  - public/geo/countries-110m.json: Natural Earth 1:110m country outlines (public domain), reduced to
 *    an ISO code and a name per country, with coordinates rounded to ~1 km to keep the file small.
 *  - src/lib/atlas/continents.ts: ISO country code -> continent, from GeoNames countryInfo (CC BY 4.0).
 *
 *   node scripts/data/build-geo.mjs
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const NATURAL_EARTH =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson";
const COUNTRY_INFO = "https://download.geonames.org/export/dump/countryInfo.txt";
const CONTINENT_NAMES = {
  AF: "Africa",
  AN: "Antarctica",
  AS: "Asia",
  EU: "Europe",
  NA: "North America",
  OC: "Oceania",
  SA: "South America",
};

async function get(url) {
  const response = await fetch(url, { headers: { "User-Agent": "voyager-local-setup" } });
  if (!response.ok) throw new Error(`Download failed (${response.status}) for ${url}`);
  return response;
}

const round = (value) => (Array.isArray(value) ? value.map(round) : Math.round(value * 100) / 100);

const world = await (await get(NATURAL_EARTH)).json();
const features = [];
const missingCode = [];
for (const feature of world.features) {
  // ISO_A2_EH fills the gaps ISO_A2 leaves as "-99" (France, Norway, Kosovo...).
  const iso = feature.properties.ISO_A2_EH;
  if (!/^[A-Z]{2}$/.test(iso)) {
    missingCode.push(feature.properties.NAME);
    continue;
  }
  features.push({
    type: "Feature",
    properties: { iso, name: feature.properties.NAME },
    geometry: { type: feature.geometry.type, coordinates: round(feature.geometry.coordinates) },
  });
}
mkdirSync(join(ROOT, "public", "geo"), { recursive: true });
writeFileSync(
  join(ROOT, "public", "geo", "countries-110m.json"),
  JSON.stringify({ type: "FeatureCollection", features }),
);
console.log(`Wrote ${features.length} country outlines`);
if (missingCode.length) console.warn(`No ISO code, left out: ${missingCode.join(", ")}`);

const info = await (await get(COUNTRY_INFO)).text();
const entries = [];
for (const line of info.split("\n")) {
  if (line.startsWith("#") || !line.trim()) continue;
  const fields = line.split("\t");
  const iso = fields[0];
  const continent = fields[8];
  if (/^[A-Z]{2}$/.test(iso) && continent in CONTINENT_NAMES)
    entries.push(`  ${iso}: "${continent}",`);
}
writeFileSync(
  join(ROOT, "src", "lib", "atlas", "continents.ts"),
  [
    "// Generated by scripts/data/build-geo.mjs from GeoNames countryInfo (CC BY 4.0). Do not edit.",
    "",
    `export const CONTINENT_NAMES = ${JSON.stringify(CONTINENT_NAMES, null, 2)} as const;`,
    "",
    "export type ContinentCode = keyof typeof CONTINENT_NAMES;",
    "",
    "export const CONTINENT_BY_COUNTRY: Readonly<Record<string, ContinentCode>> = {",
    ...entries,
    "};",
    "",
  ].join("\n"),
);
console.log(`Wrote ${entries.length} country-continent pairs`);

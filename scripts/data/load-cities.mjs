#!/usr/bin/env node
/**
 * Builds supabase/seed/cities.sql from GeoNames (https://www.geonames.org, CC BY 4.0):
 * every populated place with 15,000+ people, plus first-level region names for disambiguation.
 *
 *   npm run data:cities   # then: npm run db:reset (applies migrations, then seeds)
 *
 * The generated SQL is a build artefact (gitignored); the downloads are cached next to it.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SEED_DIR = join(ROOT, "supabase", "seed");
const CACHE_DIR = join(SEED_DIR, ".cache");
const OUT = join(SEED_DIR, "cities.sql");
const SOURCES = {
  cities: "https://download.geonames.org/export/dump/cities15000.zip",
  admin1: "https://download.geonames.org/export/dump/admin1CodesASCII.txt",
};
const BATCH = 1000;

async function download(url, file) {
  if (existsSync(file)) return;
  const response = await fetch(url, { headers: { "User-Agent": "voyager-local-setup" } });
  if (!response.ok) throw new Error(`Download failed (${response.status}) for ${url}`);
  writeFileSync(file, Buffer.from(await response.arrayBuffer()));
}

function sqlText(value) {
  return value === null ? "null" : `'${value.replaceAll("'", "''")}'`;
}

function parseAdmin1(text) {
  const names = new Map();
  for (const line of text.split("\n")) {
    const [code, , ascii] = line.split("\t");
    if (code && ascii) names.set(code, ascii);
  }
  return names;
}

function parseCities(text, admin1) {
  const rows = [];
  const skipped = new Map();
  const skip = (reason) => skipped.set(reason, (skipped.get(reason) ?? 0) + 1);

  for (const line of text.split("\n")) {
    if (!line.trim()) continue;
    const f = line.split("\t");
    const [id, name, ascii, , lat, lng, , , country, , admin1Code, , , , population, , , timezone] =
      f;
    const latitude = Number(lat);
    const longitude = Number(lng);
    if (!/^\d+$/.test(id ?? "")) {
      skip("bad id");
      continue;
    }
    if (!name || !ascii) {
      skip("missing name");
      continue;
    }
    if (!/^[A-Z]{2}$/.test(country ?? "")) {
      skip("bad country code");
      continue;
    }
    if (!Number.isFinite(latitude) || Math.abs(latitude) > 90) {
      skip("bad latitude");
      continue;
    }
    if (!Number.isFinite(longitude) || Math.abs(longitude) > 180) {
      skip("bad longitude");
      continue;
    }
    rows.push({
      id: Number(id),
      name: name.slice(0, 200),
      ascii: ascii.slice(0, 200),
      country,
      region: admin1.get(`${country}.${admin1Code}`)?.slice(0, 200) ?? null,
      latitude,
      longitude,
      population: /^\d+$/.test(population ?? "") ? Number(population) : 0,
      timezone: timezone || null,
    });
  }
  return { rows, skipped };
}

function toSql(rows) {
  const out = [
    "-- Generated by scripts/data/load-cities.mjs from GeoNames (CC BY 4.0). Do not edit.",
    "begin;",
  ];
  for (let i = 0; i < rows.length; i += BATCH) {
    const values = rows
      .slice(i, i + BATCH)
      .map(
        (r) =>
          `(${r.id},${sqlText(r.name)},${sqlText(r.ascii)},'${r.country}',${sqlText(r.region)},${r.latitude},${r.longitude},${r.population},${sqlText(r.timezone)})`,
      );
    out.push(
      "insert into public.cities (geoname_id, name, ascii_name, country_code, region, latitude, longitude, population, timezone) values",
      values.join(",\n") + "\non conflict (geoname_id) do nothing;",
    );
  }
  out.push("commit;", "");
  return out.join("\n");
}

mkdirSync(CACHE_DIR, { recursive: true });
const zip = join(CACHE_DIR, "cities15000.zip");
const admin1File = join(CACHE_DIR, "admin1CodesASCII.txt");
await download(SOURCES.cities, zip);
await download(SOURCES.admin1, admin1File);

const citiesText = execFileSync("unzip", ["-p", zip, "cities15000.txt"], {
  maxBuffer: 64 * 1024 * 1024,
}).toString("utf8");
const { rows, skipped } = parseCities(citiesText, parseAdmin1(readFileSync(admin1File, "utf8")));
if (rows.length < 20_000)
  throw new Error(`Only ${rows.length} cities parsed; the download looks incomplete.`);

writeFileSync(OUT, toSql(rows));
console.log(`Wrote ${rows.length} cities to ${OUT}`);
for (const [reason, count] of skipped) console.warn(`Skipped ${count} row(s): ${reason}`);
